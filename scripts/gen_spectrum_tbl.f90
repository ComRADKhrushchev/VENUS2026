!=====================================================================
! gen_spectrum_tbl.f90 - MANUAL spectrum-table generator for a diatomic
!   record (the equivalence criterion's anti-hand-copy instrument,
!   docs/plans/2026-10-05-spectrum-source.md §6.1: the stretch column
!   comes from stretch_mode itself and the frequency rides the same
!   wvn face the reader converts on the way back, so the file's round
!   trip reproduces the withdrawn container-export doubles bit for bit;
!   es24.16 round-trips real(8))
! Usage:
!   gen_spectrum_tbl <out.tbl> <sym1> <sym2> <x1> <y1> <z1> <x2> <y2> <z2> <w_e> <w_ex_e> <B_e>
!   (coordinates = the fragment's buffered geometry from the case's
!   system/ file, Angstrom; masses via elem_mass - the engine's table)
! Compile (from src/, against the built objects):
!   gfortran -O2 -Jbuild -o ../scripts/gen_spectrum_tbl.exe &
!            ../scripts/gen_spectrum_tbl.f90 build/gfortran/utils/specio.o &
!            build/gfortran/utils/spectrum.o build/gfortran/utils/linalg.o &
!            build/gfortran/globals/consts.o
!=====================================================================
program gen_spectrum_tbl
   use specio,   only: elem_mass
   use spectrum, only: stretch_mode
   implicit none
   character(len=64) :: args(12)
   real(8) :: qz(6), mass(2), c(6), we, wx, be
   integer :: i, u, ios
   do i = 1, 12
      call get_command_argument(i, args(i))
      if (len_trim(args(i)) == 0) then
         write (0, '(a)') 'gen_spectrum_tbl: needs 12 arguments: out sym1 sym2 x1 y1 z1 x2 y2 z2 we wx be'
         stop 1
      end if
   end do
   read (args(4), *, iostat=ios) qz(1)
   read (args(5), *, iostat=ios) qz(2)
   read (args(6), *, iostat=ios) qz(3)
   read (args(7), *, iostat=ios) qz(4)
   read (args(8), *, iostat=ios) qz(5)
   read (args(9), *, iostat=ios) qz(6)
   read (args(10), *, iostat=ios) we
   read (args(11), *, iostat=ios) wx
   read (args(12), *, iostat=ios) be
   if (ios /= 0) then
      write (0, '(a)') 'gen_spectrum_tbl: a numeric argument failed to parse'
      stop 1
   end if
   mass = [elem_mass(trim(args(2))), elem_mass(trim(args(3)))]
   call stretch_mode(qz, mass, c)
   open (newunit=u, file=trim(args(1)), status='replace', action='write')
   write (u, '(a)') '# manual spectrum table - generated by gen_spectrum_tbl (stretch_mode column)'
   write (u, '(a,1x,a,1x,a)') 'FRAG', trim(args(2)), trim(args(3))
   write (u, '(a,1x,i0)') 'NMODE', 1
   write (u, '(a,1x,es24.16)') 'WVN', we
   write (u, '(a,1x,i0)') 'COL', 1
   write (u, '(6es25.16)') c
   write (u, '(a,1x,3(1x,es24.16))') 'DIAT', we, wx, be
   close (u)
end program gen_spectrum_tbl
