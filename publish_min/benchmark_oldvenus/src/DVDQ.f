      SUBROUTINE DVDQ
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      INCLUDE 'SIZES'
C
C         CALCULATE POTENTIAL ENERGY PARTIAL DERIVATIVES WITH 
C         RESPECT TO COORDINATES (PDOT)
C
      COMMON/FORCES/NATOMS,I3N,NFC,NGLO
      COMMON/QPDOT/Q(NDA3),PDOT(NDA3),FCOEF(NDA3,NDA3)
      COMMON/PQDOT/P(NDA3),QDOT(NDA3),W(NDA)
      COMMON/GLOP/WS1(3),WG1(3),WS2(3),WG2(3),WGS1(3),WGS2(3),WEFF(3)
     &,GSW,FCG,COEFA,COEFB,GN(NDA3)
      COMMON/FRAGB/WTA(NDP),WTB(NDP),LA(NDP,NDA),LB(NDP,NDA),
     *QZA(NDP,NDA3),QZB(NDP,NDA3),NATOMA(NDP),NATOMB(NDP)
      COMMON/CONSTN/C1,C2,C3,C4,C5,C6,C7,PI,HALFPI,TWOPI
      COMMON/GAUSS/ICHRG,IMULTP,IAN(NDAYF),VGAUSS
      COMMON/GAUSS2/GAUHES(NDIHE)
      COMMON/VRSCAL/THERMOTEMP,NSEL,NSCALE,NEQUAL,NRGD
      DIMENSION AHESS(NDIHE)
      LOGICAL SAVFIL,OK
C
C         ZERO PDOT'S
C
      DO I=1,I3N
         PDOT(I)=0.0D0
      ENDDO

!     ADAPTED BY BIN 8/6/2016
C     NOW: CALCULATE PARTIALS FOR USER CUSTOMED POTENTIAL ENERGY
      IF (NGLO.EQ.0) THEN
         CALL DPESHON(NATOMS)
      ELSE
         CALL DPESHON(NATOMS-1)
      ENDIF
!     END
C
   !   DO I=1,I3N       Modified by CZZ 2024/3/9
   !      PDOT(I)=-PDOT(I)
   !   ENDDO

      RETURN
      END
