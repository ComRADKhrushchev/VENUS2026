      SUBROUTINE BAREXC(WT,C,AM,EROT,N,NM)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      INCLUDE 'SIZES'
C
C         BARRIER EXCITATION
C         SELECT MOMENTA FOR THE REACTION COORDINATE
C
      COMMON/PRLIST/T,V,H,TIME,NTZ,NT,ISEED0(8),NC,NX
      COMMON/WASTE/QQ(NDA3),PP(NDA3),WX,WY,WZ,L(NDA),NAM
      COMMON/QPDOT/Q(NDA3),PDOT(NDA3),FCOEF(NDA3,NDA3)
      COMMON/PQDOT/P(NDA3),QDOT(NDA3),W(NDA)
      COMMON/CONSTN/C1,C2,C3,C4,C5,C6,C7,PI,HALFPI,TWOPI
      COMMON/SADDLE/EBAR,TBAR,EZERO,NBAR,IDIR,JDIR,IJDIR 
      DIMENSION C(NDA3yf,NDA3yf),QCM(3),VCM(3)
    5 FORMAT(/4X,'REACTION COORDINATE ENERGY =',1PE18.9,' KCAL/MOL'/)
   15 FORMAT(15X,'INTERNAL ENERGY =',1PE18.9,' KCAL/MOL'/)
C
C         CALCULATE VELOCITY FOR REACTION COORDINATE
C         THE REACTION COORDINATE IS HELD FIXED 
C
C                 FIXED ENERGY FOR REACTION COORDINATE
C
      RAND=RAND0(ISEED)
      IF(NBAR.NE.2) THEN
         SDUM=C1*EBAR
         PBAR=SQRT(2*SDUM)
C
C                 FIXED TEMPERATURE FOR REACTION COORDINATE
C
      ELSEIF(NBAR.EQ.2) THEN
         DUM=LOG(1.0D0-RAND)
         PBAR=SQRT(-2.0D0*C5*TBAR*DUM)
      ENDIF
C
      WRITE(6,5)0.5D0*PBAR*PBAR/C1

      IF (IJDIR.NE.0) THEN
C
C        DIRECT TRAJECTORY TOWARDS PRODUCTS IF IJDIR = 1
C        AND TOWARDS REACTANTS IF IJDIR = -1
C
        DT = 0.1D0
C
C        DT IS AN ARBITRARY, SMALL STEP IN THE "POSITIVE" IRC
C        DIRECTION
C 
        DO I=1,N
           DO K=1,3
              JJ=3*I+1-K
              J=3*L(I)+1-K
              QQ(J)=Q(J)+C(JJ,NM)*DT
           ENDDO
        ENDDO
        DUM1=0.0D0
        DUM=0.0D0
        I=IDIR
        J=JDIR
        II=3*I
        JJ=3*J
        DO K=1,3
           DUM1=DUM1+(QQ(II)-QQ(JJ))**2
           DUM=DUM+(Q(II)-Q(JJ))**2
           II=II-1
           JJ=JJ-1
        ENDDO
        DUM=SQRT(DUM1)-SQRT(DUM)
        IF(IJDIR.LT.0.0D0.AND.DUM.GT.0.0D0) PBAR=-PBAR
        IF(IJDIR.GT.0.0D0.AND.DUM.LT.0.0D0) PBAR=-PBAR
      ELSE
        IF (RAND.GE.0.5D0) PBAR=-PBAR
      ENDIF   

C
C         ADD IRC MOMENTUM AND TRANSFORM FROM NORMAL MODE TO CARTESIAN VELOCITY
C
      DO I=1,N
         DO K=1,3
            JJ=3*I+1-K
            J=3*L(I)+1-K
            P(J)=P(J)+C(JJ,NM)*PBAR*W(L(I))
         ENDDO
      ENDDO
C
C         CALCULATE CENTER OF MASS COORDINATES QQ AND MOMENTA PP
C
      CALL CENMAS(WT,QCM,VCM,N)
C
C         MOVE PP ARRAY TO P ARRAY AND QQ ARRAY TO Q ARRAY
C
      DO I=1,N
         J=3*L(I)+1
         DO K=1,3
            Q(J-K)=QQ(J-K)
            P(J-K)=PP(J-K)
         ENDDO
      ENDDO
      CALL DVDQ
      CALL ENERGY
C
      CALL ROTN(AM,EROT,N)
C
      EINT=H-EZERO
      WRITE(6,15)EINT
C
      RETURN
      END
