      SUBROUTINE ROTATEY(CSTHTA,N)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      INCLUDE 'SIZES'
C
C         RANDOMLY ROTATE A MOLECULE ABOUT ITS CENTER OF MASS BY
C         EULER'S ANGLES.
C
      COMMON/QPDOT/Q(NDA3),PDOT(NDA3),FCOEF(NDA3,NDA3)
      COMMON/PQDOT/P(NDA3),QDOT(NDA3),W(NDA)
      COMMON/WASTE/QQ(NDA3),PP(NDA3),WX,WY,WZ,L(NDA),NAM
      COMMON/SELTB/QZ(NDA3),NSELT,NSFLAG,NACTA,NACTB,NLINA,NLINB,NSURF
      COMMON/CONSTN/C1,C2,C3,C4,C5,C6,C7,PI,HALFPI,TWOPI
C
C         CENTER OF MASS COORDINATES(QQ) AND MOMENTA(PP) ARE PASSED FROM
C         SUBROUTINES CENMAS AND ANGVEL THROUGH COMMON BLOCK WASTE.
C
      THTA=ACOS(CSTHTA)
      SNTHTA=SIN(THTA)
      DO I=1,N
      J=3*L(I)
         Q(J-2)=QQ(J-2)*CSTHTA+QQ(J)*SNTHTA
         Q(J-1)=QQ(J-1)
         Q(J)=-QQ(J-2)*SNTHTA+QQ(J)*CSTHTA
         QQ(J-2)=Q(J-2)
         QQ(J-1)=Q(J-1)
         QQ(J)=Q(J)
         P(J-2)=PP(J-2)*CSTHTA+PP(J)*SNTHTA
         P(J-1)=PP(J-1)
         P(J)=-PP(J-2)*SNTHTA+PP(J)*CSTHTA
         PP(J-2)=P(J-2)
         PP(J-1)=P(J-1)
         PP(J)=P(J)
      ENDDO
      RETURN
      END
