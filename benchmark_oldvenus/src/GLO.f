      SUBROUTINE GLOINIT
      INCLUDE 'SIZES'
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      COMMON/GLOP/WS1(3),WG1(3),WS2(3),WG2(3),WGS1(3),WGS2(3),WEFF(3)
     &,GSW,FCG,COEFA,COEFB,GN(NDA3)
      COMMON/CONSTN/C1,C2,C3,C4,C5,C6,C7,PI,HALFPI,TWOPI
!.....UNIT CONVERSION 
      FACTOR1=413.4D0                                         !-->TIME^-1, CONVERT FRICTION COEFFICIENT TO VENUS'S UNIT (10FS)^-1
      FACTOR2=413.4D0                                         !-->CONVERT FREQUENCY TO VENUS'S UNIT (10FS)^-1
      FCG=FCG*FACTOR1
      DO I=1,3
         WS1(I)=WS1(I)*FACTOR2
         WS2(I)=WS1(I)**2
      ENDDO
      DO I=1,3
         WG1(I)=WG1(I)*FACTOR2
         WG2(I)=WG1(I)**2
      ENDDO
      DO I=1,3
         WGS1(I)=WS1(I)
         WGS2(I)=WS1(I)*WG1(I)
         WEFF(I)=DSQRT(2D0*WS2(I)-WGS1(I)**2)
      ENDDO
      END

      SUBROUTINE GLOSELECT(TVIBB)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      INCLUDE 'SIZES'
      COMMON/PRLIST/T,V,H,TIME,NTZ,NT,ISEED0(8),NC,NX
      COMMON/PQDOT/P(NDA3),QDOT(NDA3),W(NDA)
      COMMON/QPDOT/Q(NDA3),PDOT(NDA3),FCOEF(NDA3,NDA3)
      COMMON/GLOP/WS1(3),WG1(3),WS2(3),WG2(3),WGS1(3),WGS2(3),WEFF(3)
     &,GSW,FCG,COEFA,COEFB,GN(NDA3)
      COMMON/FRAGB/WTA(NDP),WTB(NDP),LA(NDP,NDA),LB(NDP,NDA),
     *QZA(NDP,NDA3),QZB(NDP,NDA3),NATOMA(NDP),NATOMB(NDP)
      COMMON/INTEGR/ATIME,NI,NID
      COMMON/CONSTN/C1,C2,C3,C4,C5,C6,C7,PI,HALFPI,TWOPI
      BOLTZ=8.6173D-5*23.0605D0*C1
      RBOHR=0.5291772D0
      FACTOR=DSQRT(TVIBB*BOLTZ*W(NATOMA(1)+1))
      FACTOR2=DSQRT(627.509D0*C1*1822.89D0)
      DO I=1,3
        G1=GASDEV(ISEED)
        G2=GASDEV(ISEED)
        G3=GASDEV(ISEED)
        G4=GASDEV(ISEED)
         J=3*(NATOMA(1))+I
         K=3*(NATOMA(1)+1)+I
         Q(J)=FACTOR*G1/WEFF(I)/W(NATOMA(1)+1)
         P(J)=FACTOR*G2
         Q(K)=FACTOR*G3/WG1(I)/W(NATOMA(1)+1)+WGS1(I)*Q(J)/WG1(I)
         P(K)=FACTOR*G4
      ENDDO
c      FCG=0D0   !REMOVE DAMPING FORCE AND WHITE NOISE FOR CHECKING THE CONSERVATION, OTHERWISE, COMMENT THIS LINE
      COEFA=(1-FCG*ATIME*0.5D0)/(1+FCG*ATIME*0.5D0)
      COEFB=1D0/(1+FCG*ATIME*0.5D0)
      GSW=DSQRT(2D0*BOLTZ*TVIBB*FCG*W(NATOMA(1)+1)*ATIME)
      END

      SUBROUTINE GLOEQU(TVIBB)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      INCLUDE 'SIZES'
      COMMON/PRLIST/T,V,H,TIME,NTZ,NT,ISEED0(8),NC,NX
      COMMON/PQDOT/P(NDA3),QDOT(NDA3),W(NDA)
      COMMON/QPDOT/Q(NDA3),PDOT(NDA3),FCOEF(NDA3,NDA3)
      COMMON/FORCES/NATOMS,I3N,NFC,NGLO
      COMMON/GLOP/WS1(3),WG1(3),WS2(3),WG2(3),WGS1(3),WGS2(3),WEFF(3)
     &,GSW,FCG,COEFA,COEFB,GN(NDA3)
      COMMON/FRAGB/WTA(NDP),WTB(NDP),LA(NDP,NDA),LB(NDP,NDA),
     *QZA(NDP,NDA3),QZB(NDP,NDA3),NATOMA(NDP),NATOMB(NDP)
      COMMON/INTEGR/ATIME,NI,NID
      COMMON/CONSTN/C1,C2,C3,C4,C5,C6,C7,PI,HALFPI,TWOPI
      COMMON/QPSCAL/QTEMP(NDA3),PTEMP(NDA3)
      COMMON/SFEQUIL/INTEGRATOR,LLL,NITER
      DIMENSION FT(NDA3),QTP1(NDA3),QTM1(NDA3),QTP2(NDA3),QTM2(NDA3)

      N=NATOMA(1)

      NC=0

      NSE=30000 ! FOR EQULIBRATION

!.....FOR GLO MODEL, ADDITIONAL FROCES
      DO K=1,I3N
         PDOT(K)=0.0D0
      ENDDO

      DO II=1,3
        J=3*(NATOMA(1))+II
        K=3*(NATOMA(1)+1)+II
        I1=NATOMA(1)+1
        I2=NATOMA(1)+2
        PDOT(J)=PDOT(J)-2D0*WS2(II)*W(I1)*Q(J)+WGS2(II)*W(I1)*Q(K)
        PDOT(K)=PDOT(K)-2D0*WG2(II)*W(I2)*Q(K)+WGS2(II)*W(I2)*Q(J)
      ENDDO

      TB=0.D0
      DO I=1,NSE
         NC=NC+1

         DO K=NI-5,NI-3
           KK=(K+2)/3
           FT(K)=PDOT(K)
           Q(K)=Q(K)+P(K)*ATIME/W(KK)+PDOT(K)/(2.D0*W(KK))*ATIME**2
         ENDDO

         DO K=NI-2,NI
           KK=(K+2)/3
           GN(K)=GASDEV(IDUM)*GSW
           FT(K)=PDOT(K)
           Q(K)=Q(K)+COEFB*ATIME*P(K)/W(KK)+COEFB*ATIME**2*0.5D0*PDOT(K)
     &/W(KK)+COEFB*ATIME*0.5D0*GN(K)/W(KK)
         ENDDO

!...UPDATE VELOCITY (MOMENTUM)
         DO K=1,I3N
            PDOT(K)=0.0D0
         ENDDO

!.....FOR GLO MODEL
         DO II=1,3
           J=3*(NATOMA(1))+II
           K=3*(NATOMA(1)+1)+II
           I1=NATOMA(1)+1
           I2=NATOMA(1)+2
           PDOT(J)=PDOT(J)-2D0*WS2(II)*W(I1)*Q(J)+WGS2(II)*W(I1)*Q(K)
           PDOT(K)=PDOT(K)-2D0*WG2(II)*W(I2)*Q(K)+WGS2(II)*W(I2)*Q(J)
         ENDDO
C
C   P=MV SO P(T+DT)=P(T)+(F(T+DT)+F(T))*DT/2
C
         DO K=NI-5,NI-3
           P(K)=P(K)+(FT(K)+PDOT(K))*ATIME*0.5D0
         ENDDO
 
         DO K=NI-2,NI
           P(K)=COEFA*P(K)+ATIME*0.5D0*(COEFA*FT(K)+PDOT(K))+COEFB*GN(K)
         ENDDO

         DO II=N+1,NATOMS
           J3=II*3
           J2=J3-1
           J1=J3-2
           TB=TB+(P(J1)**2+P(J2)**2+P(J3)**2)/W(II)
         ENDDO
         TEMP=TB/(3.0D0*DBLE(NATOMS-N)*0.00198717D0*C1)/NC
         IF (NC.EQ.NC/1000*1000) THEN
            WRITE(30,'(A,2F12.2)')'SELECTED AND CURRENT TEMPERATURE='
     &      ,TVIBB,TEMP
         ENDIF
      ENDDO
      WRITE(30,*)
C
      WRITE(6,*)'EQUALIBRATION FOR GLO MODEL IS NOW OVER'
C
      NC=0
C
      END SUBROUTINE GLOEQU
