      SUBROUTINE MAINLZ(QDUM,NCHKP)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      INCLUDE 'SIZES'  
      
C     THIS SUBROUTINE COORDINATES THE CALCULATIONS 
C     FOR NSELT = -3, -2, AND -1                        
C     
C     NSELT = -3, STATIONARY POINT SEARCH
C     NSELT = -2, REACTION PATH AND CVTST RATE CONSTANTSIS
C     NSELT = -1, NORMAL MODE ANALYSIS  

      COMMON/SELTB/QZ(NDA3),NSELT,NSFLAG,NACTA,NACTB,NLINA,NLINB,NSURF
      COMMON/RSTART/HINC,NPTS  
      COMMON/FORCES/NATOMS,I3N,NFC,NGLO
      COMMON/FRAGB/WTA(NDP),WTB(NDP),LA(NDP,NDA),LB(NDP,NDA),
     *QZA(NDP,NDA3),QZB(NDP,NDA3),NATOMA(NDP),NATOMB(NDP)
      COMMON/WASTE/QQ(NDA3),PP(NDA3),WX,WY,WZ,LL(NDA),NAM
      COMMON/QPDOT/Q(NDA3),PDOT(NDA3),FCOEF(NDA3,NDA3)
      COMMON/PQDOT/P(NDA3),QDOT(NDA3),W(NDA)
      COMMON/RANCOM/RANLST(100),ISEED3(8),IBFCTR
      COMMON/PRLIST/T,V,H,TIME,NTZ,NT,ISEED0(8),NC,NX
      COMMON/PRFLAG/NFQP,NCOOR,NFR,NUMR,NFB,NUMB,NFA,NUMA,NFTAU,NUMTAU,
     *NFTET,NUMTET,NFDH,NUMDH,NFHT,NUMHT
      COMMON/VRSCAL/THERMOTEMP,NSEL,NSCALE,NEQUAL,NRGD
      
      DIMENSION QDUM(NDA3)
      
  890 FORMAT(/'   AN ERROR OCCURRED : THE CHECKPOINT FILE COULD',
     *   ' NOT BE READ')
  894 FORMAT(/5X,'COORDINATES AND MOMENTA ARE READ IN FROM ',
     *'CHECKPOINT FILE'/5X,'READING FROM UNIT 50'/)
  897 FORMAT(5X,47HCALCULATIONS ARE RESTARTED FROM CHECKPOINT FILE,
     */5X,'READING FROM UNIT 50'//)
  900 FORMAT('  MEP AS IN VENUS96'//)
  901 FORMAT('  MEP AND CVTST RATE CONSTANT'//)
  902 FORMAT('  MEP AND CVTST RATE CONSTANT, WITH REACTANT 
     *PROPERTIES'//)
  925 FORMAT('  PARAMETERS FOR CALCULATING FREQUENCIES'/'   HINC=',F9.6,
     *5X,'NPTS=',I2//)
  971 FORMAT(23X,'NORMAL MODE ANALYSIS'//)                 
  972 FORMAT(22X,'REACTION PATH FOLLOWING'/)
  973 FORMAT(22X,'STATIONARY POINT SEARCH'//)
C
C         TO CALCULTE VIBRATIONAL FREQUENCIES,
C         READ DISPLACEMENT INTERVAL, HINC, AND 
C         READ NUMBER OF DISPLACEMENTS ABOUT CARTESIAN MININUM, NPTS.
C
      READ(5,*)HINC,NPTS      
      WRITE(6,925)HINC,NPTS   
C
      IF (NSELT.EQ.-1) WRITE(6,971)
      IF (NSELT.EQ.-2) WRITE(6,972)
      IF (NSELT.EQ.-3) WRITE(6,973)
C     
C         READ OPTION FOR NSELT = -2
C         
      IF (NSELT.EQ.-2) THEN
         READ(5,*)NMEP
         IF (NMEP.EQ.0) WRITE(6,900)
         IF (NMEP.EQ.1) WRITE(6,901)
         IF (NMEP.EQ.2) WRITE(6,902)
C
C         FOR NSELT = -2, READ PARAMETERS FOR REACTANTS
C
C         PARAMETERS FOR REACTANT A
C
      READ(5,*)NATOMA(1),NLINA
      K=NATOMA(1)
      WTA(1)=0.0D0
      DO J=1,K
         LA(1,J)=J
         LL(J)=LA(1,J)
         WTA(1)=WTA(1)+W(J)
      ENDDO
C
C         PARAMETERS FOR REACTANT B
C
      READ(5,*)NATOMB(1),NLINB  
      K=NATOMB(1)
      WTB(1)=0.0D0
      DO J=1,K
         M=J+NATOMA(1)
         LB(1,J)=M
         LL(J)=LB(1,J)
         WTB(1)=WTB(1)+W(M)
      ENDDO
      ENDIF
C
C         READ PARAMETERS FOR PRINTING INFORMATION
C          
      IF (NSELT.NE.-1) CALL PRINFO
C
C         SET FLAGS AND PARAMETERS
C        
      NI=I3N-NRGD*3
      NID=2*NI
C      
C         DETERMINE THE STARTING TIME.
C
      CALL CPUSEC(TUSER1,TTOTAL1)
      SECADD=0.0D0      
C
C         CHECKPOINT FILE TO START THE TRAJECTORY
C
C         IF NCHKP .NE. 0 THEN CALCULATIONS ARE RESTARTED FROM CHECKPOINT
C         FILE (ANY TYPE OF VENUS CALCULATION PRODUCES A CHECKPOINT FILE
C         IN UNIT 50, WHICH CONTAINS Q,P,QDOT,etc. AND THE RANDOM NUMBER
C         GENERATOR INFORMATION).
C
C         IF NCHKP IS 1, CALCULATIONS ARE RESTARTED WHERE LEFT, IN
C         CASE OF A COMPUTER CRASH, OR UNDER-ESTIMATION OF THE CYCLE
C         NUMBER IN REACTION PATH FOLLOWING, NUMBER OF TRAJECTORIES,
C         ETC. (THE CODE FOLLOWS INPUT UPDATES)
C
C         IF NCHKP IS -1, NEW CALCULATIONS ARE STARTED WITH CARTESIAN
C         COORDINATES AND MOMENTA READ FROM CHECKPOINT FILE. FOR EXAMPLE,
C         ONE CAN PERFORM A SEQUENCE OF CALCULATIONS WITH THIS OPTION :
C         MINIMUM ENERGY SEARCH, REFINEMENT BY REACTION PATH FOLLOWING,
C         NORMAL MODE ANALYSIS, WHERE Q AND P'S CAN BE PASSED THRU THE
C         CHECKPOINT FILE. THIS OPTION IS AVAILABLE FOR NSELT .NE. 2 ONLY.
C
C
      IF(NCHKP.EQ.0)GOTO 223
C
C      OPEN(50,FORM='UNFORMATTED')
C      READ(50,ERR=222)Q,P,QDOT,PDOT,TABLE,VRELO,RANLST,GTEMP,NFLAG,
C     *ISEED0,ISEED3,NX,NC,NTZ,INTST,NAST,IBFCTR,
C     *VI,OAMI,AMAI,AMBI,ETAI,ERAI,ETBI,ERBI
C      CLOSE(50)      
C
      CALL DVDQ
      CALL ENERGY
      IF (NCHKP.EQ.-1) WRITE(6,894)
      IF (NCHKP.EQ.1) WRITE(6,897)     
     
         IF (NSELT.NE.-3.OR.NCHKP.EQ.-1) NTZ=1
         NDUM=MAX0(1,NTZ)
         DO J=1,NDUM
            READ(5,*)(QDUM(I),I=1,I3N)
         ENDDO
         DO I=1,I3N
            P(I)=0.0D0
         ENDDO
         IF (NCHKP.EQ.-1) THEN
            NC=0
            NX=0
         ENDIF
C  
C      CALCULATIONS ARE STARTED FROM CHECKPOINT FILE
C
      IF (NCOOR.EQ.1.AND.NSELT.EQ.-2)  CALL SYBMOL
      CALL GWRITE
C
      I=0
      IF (NSELT.EQ.-1) CALL NMODE(NATOMS,I)
C
C         KI ADDED MPATHO TO KEEP COMPATIBILITY WITH VENUS96C
C
      IF (NSELT.EQ.-2) then
         IF(NMEP.EQ.0) THEN
           CALL MPATHO
         ELSE
           CALL MPATH
         ENDIF
      ENDIF
C
      CALL GWRITE
      IF (NSELT.EQ.-3) CALL STATPT
C
C    DETERMINE THE COMPUTATION TIME
C
      CALL CPUSEC(TUSER2,TTOTAL2)
      WRITE(6,515) (SECADD+TUSER2-TUSER1),(SECADD+TTOTAL2-TTOTAL1)
  515 FORMAT(//' USER AND REAL TIME FOR VENUS:',
     *       2F8.1,' SECONDS'//)
  222 WRITE(6,890)
      STOP
C
C    START THE CALCULATION WITH COORDINATES FROM SELECT
C
  223 CONTINUE
C
      CALL SELECT
C
C      OPEN(50,FORM='UNFORMATTED')
C      REWIND(50)
C      WRITE(50)Q,P,QDOT,PDOT,TABLE,VRELO,RANLST,GTEMP,NFLAG,ISEED0,
C     *ISEED3,NX,NC,NTZ,INTST,NAST,IBFCTR,
C     *VI,OAMI,AMAI,AMBI,ETAI,ERAI,ETBI,ERBI
C      CLOSE(50)
C
      IF (NCOOR.EQ.1.AND.NSELT.EQ.-2) CALL SYBMOL
C
      IF (NSELT.EQ.-1) NFQP=1
      CALL GWRITE
C
      I=0
      IF (NSELT.EQ.-1) CALL NMODE(NATOMS,I)
C
C         KI ADDED MPATHO TO KEEP COMPATIBILITY WITH VENUS96C
C
      IF (NSELT.EQ.-2) then
         IF(NMEP.EQ.0) THEN
           CALL MPATHO
         ELSE
           CALL MPATH
         ENDIF
      ENDIF
C
      IF (NSELT.EQ.-3) CALL STATPT
C
C    DETERMINE THE COMPUTATION TIME
C
      CALL CPUSEC(TUSER2,TTOTAL2)
      WRITE(6,515) (SECADD+TUSER2-TUSER1),(SECADD+TTOTAL2-TTOTAL1)
      STOP
      END
C
