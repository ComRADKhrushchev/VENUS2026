subroutine ROTATENO(N, NTHTA)
  use venus_params
  implicit none
  integer,  intent(in)    :: N, NTHTA
  real(8)  :: RAND, RTHTA, CSTHTA, PTHETA, PTEST
  integer  :: ISEED
  real(8), external :: RAND0
!
!         RANDOMLY ROTATE THE SOLID ANGLE BETWEEN N->O VECTOR AND
!         SURFACE NORMAL (Z AXIS PARALLEL TO ELECTRIC FIELD).
!         SAMPLE THE SOLID ANGLE THETA TO SATISFY
!         ITS DISTRIBUTION FUNCTION IN START ELECTRIC FIELD IN THE
!         FOLLOWING FORM:
!         P(THETA)=(1-COSTHETA)/2  FOR POSITIVE FIELD (+Z DIRECTION)
!         O-DOWN ORIENTATION
!         P(THETA)=(1+COSTHETA)/2  FOR NEGATIVE FIELD (-Z DIRECTION)
!         N-DOWN ORIENTATION
!         THIS IS DONE BY VON NEUMANN REJECTION METHOD.
!
!         CENTER OF MASS COORDINATES(QQ) AND MOMENTA(PP) ARE PASSED FROM
!         SUBROUTINES CENMAS AND ANGVEL THROUGH COMMON BLOCK WASTE.
!
!     VON NEUMANN REJECTION SAMPLING
!     INITIALIZE A RANDOM THETA VALUE
!     THETA REPRESENTS THE SOLID ANGLE WITH RESPECT TO SURFACE NORMAL (Z AXIS)
  do
     RAND = RAND0(ISEED)
     RTHTA = 2.0D0*PI*RAND-PI
     CSTHTA = cos(RTHTA)
     if (NTHTA == -2) then
        PTHETA = 0.5D0*(1-CSTHTA)
     else if (NTHTA == -3) then
        PTHETA = 0.5D0*(1+CSTHTA)
     else
        stop 'NTHTA < -3 HAS NOT BEEN DEFINED'
     end if
     PTEST = RAND0(ISEED)
     if (PTHETA >= PTEST) exit
  end do
!     END REJECTION SAMPLING

!     THE NO MOLECULE ORIGINALLY LIES ON X AXIS.
!     ROTATE THE MOLECULE ABOUT Y AXIS BY 90 DEGREE, AFTER WHICH NO LIES ON THE Z AXIS
  call ROTATEY(0d0, 2)

!     NOW THE MOLECULE IS ALONG Z AXIS
!     ROTATE THE MOLECULE ABOUT Y AXIS SO THAT THE SOLID ANGLE IS THETA
  call ROTATEY(CSTHTA, 2)

!     A RANDOM ROTATION ABOUT THE SURFACE NORMAL MAKES THE FINAL
!     DISTRIBUTION CYLINDRICALLY SYMEMTRIC WITH RESPECT TO THE SURFACE NORMAL
  call ROTATEZ(2)
end subroutine ROTATENO
