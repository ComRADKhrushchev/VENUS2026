subroutine ROTATE(N)
  use venus_params
  use venus_data
  implicit none
  integer,  intent(in)    :: N
  real(8)  :: RAND, RPHI, CSTHTA, RCHI, RTHTA, SNTHTA, SNPHI
  real(8)  :: CSPHI, SNCHI, CSCHI
  real(8)  :: RXX, RXY, RXZ, RYX, RYY, RYZ, RZX, RZY, RZZ
  integer  :: I, J, ISEED
  real(8), external :: RAND0
!
!         RANDOMLY ROTATE A MOLECULE ABOUT ITS CENTER OF MASS BY
!         EULER'S ANGLES.
!
!
!         CENTER OF MASS COORDINATES(QQ) AND MOMENTA(PP) ARE PASSED FROM
!         SUBROUTINES CENMAS AND ANGVEL THROUGH COMMON BLOCK WASTE.
!
  RAND = RAND0(ISEED)
  RPHI = TWOPI*RAND
  RAND = RAND0(ISEED)
  CSTHTA = 2.0D0*RAND-1.0D0
  RAND = RAND0(ISEED)
  RCHI = TWOPI*RAND
  RTHTA = acos(CSTHTA)
  SNTHTA = sin(RTHTA)
  SNPHI = sin(RPHI)
  CSPHI = cos(RPHI)
  SNCHI = sin(RCHI)
  CSCHI = cos(RCHI)
  RXX = CSTHTA*CSPHI*CSCHI-SNPHI*SNCHI
  RXY = -CSTHTA*CSPHI*SNCHI-SNPHI*CSCHI
  RXZ = SNTHTA*CSPHI
  RYX = CSTHTA*SNPHI*CSCHI+CSPHI*SNCHI
  RYY = -CSTHTA*SNPHI*SNCHI+CSPHI*CSCHI
  RYZ = SNTHTA*SNPHI
  RZX = -SNTHTA*CSCHI
  RZY = SNTHTA*SNCHI
  RZZ = CSTHTA
  do I = 1, N
     J = 3*LL(I)
     Q(J-2) = QQ(J-2)*RXX+QQ(J-1)*RXY+QQ(J)*RXZ
     Q(J-1) = QQ(J-2)*RYX+QQ(J-1)*RYY+QQ(J)*RYZ
     Q(J) = QQ(J-2)*RZX+QQ(J-1)*RZY+QQ(J)*RZZ
     QQ(J-2) = Q(J-2)
     QQ(J-1) = Q(J-1)
     QQ(J) = Q(J)
     P(J-2) = PP(J-2)*RXX+PP(J-1)*RXY+PP(J)*RXZ
     P(J-1) = PP(J-2)*RYX+PP(J-1)*RYY+PP(J)*RYZ
     P(J) = PP(J-2)*RZX+PP(J-1)*RZY+PP(J)*RZZ
     PP(J-2) = P(J-2)
     PP(J-1) = P(J-1)
     PP(J) = P(J)
  end do
end subroutine ROTATE

