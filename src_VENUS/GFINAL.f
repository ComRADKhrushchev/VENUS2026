      SUBROUTINE GFINAL
      use venus_params
      use venus_data
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
C
C         WRITE TRAJECTORY FINAL ANALYSIS RESULTS IN OUTPUT FILE
C
C      COMMON/TESTB/RMAX(NDP),RBAR(NDP),NTEST,NPATHS,NABJ(NDP),NABK(NDP),
C     *NPATH,NAST
!!    ADDED BY BIN, 2018/07/09 — NSID,NDELH,MPATH now in venus_data
!!    COMMON NSID,NDELH(NDP),MPATH
!!-->.END
!!    COMMON/CONSTN now in venus_params
C
C      COMMON/HTURNL/NC1FLAG,NC1,NC2,NC3,HTMIN
C
    1 FORMAT(/)
    2 FORMAT(2X,26HREACTION OCCURRED FOR PATH,I3,5X,'ENERGIES IN KCAL ',
     *'AND ANGULAR MOMENTUM IN H-BAR'/)
    3 FORMAT(2X,'RESULTS FOR FRAGMENT A')
    4 FORMAT(4X,'TRAJ:',I5,2X,'TOTAL_ENERGY=',1PE16.5,3X,'VIB.ENERGY=',
     *E16.5,3X,'ROT.ENERGY=',E16.5,' +OR- ',E16.5,/,
     *4X,'TRAJ:',I5,2X,'ANG.MOMENTUM=',E16.5)
    5 FORMAT(/2X,'RESULTS FOR FRAGMENT B')
    6 FORMAT(/2X,'RELATIVE A+B PROPERTIES')
    7 FORMAT(4X,'TRAJ:',I5,2X,'REL.TRANS.ENERGY=',1PE16.5,3X,
     *'REL.TRANS.ENERGY+CEN.POTENTIAL=',E16.5/
     *4X,'TRAJ:',I5,2X,'ORB.ANG.MOMENTUM=',E16.5,
     *3X,'FINAL_B=',E16.5/)
    8 FORMAT(2X,'SCATTERING ANGLES IN DEGREES')
    9 FORMAT(4X,'TRAJ:',I5,'  LF,JAF: ',F7.2)
   10 FORMAT(4X,'TRAJ:',I5,'  LF,JBF: ',F7.2)
   11 FORMAT(4X,'TRAJ:',I5,'  JAF,JBF:',F7.2)
   12 FORMAT(4X,'TRAJ:',I5,'  VI,VF:  ',F7.2,5X,'LI,LF:  ',F7.2)
   13 FORMAT(4X,'TRAJ:',I5,'  LI,JAF: ',F7.2)
   14 FORMAT(4X,'TRAJ:',I5,'  LI,JBF: ',F7.2)
   15 FORMAT(4X,'TRAJ:',I5,'  JAI,LI: ',F7.2,5X,'JAI,LF: ',F7.2)
   16 FORMAT(4X,'TRAJ:',I5,'  JAI,JAF:',F7.2)
   17 FORMAT(4X,'TRAJ:',I5,'  JAI,JBF:',F7.2)
   18 FORMAT(4X,'TRAJ:',I5,'  JAI,JBI:',F7.2)
   19 FORMAT(4X,'TRAJ:',I5,'  JBI,LI: ',F7.2,5X,'JBI,LF: ',F7.2)
   20 FORMAT(4X,'TRAJ:',I5,'  JBI,JAF:',F7.2)
   21 FORMAT(4X,'TRAJ:',I5,'  JBI,JBF:',F7.2)
   22 FORMAT(4X,'TRAJ:',I5,'  PRODUCT IS A DIATOM:  N=',F10.2,3X,
     *'J=',F10.2)
   23 FORMAT(4X,'TRAJ:',I5,'  INCIDENT_ANG.(THTAi,CHIi):',2F7.2,
     *5X,'SCATTERING_ANG.(THTAf,CHIf):',2F7.2)
   30 FORMAT(/4X,'TRAJ:',I5,'  LIFETIME:',F12.3,' fs'/)
   36 FORMAT('TRAJ',I5,I10,E13.4)
   37 FORMAT(1X,3F10.3,3E15.5)
   38 FORMAT('TRAJ',I5,8F10.3)
c   40 FORMAT(/'  HEIGHT PROPERTIES FOR THE INCIDENT ATOM'/
c     *4X,'TRAJ:',I5,'  NC1,NC2,NC3,HTMIN:',3I7,F7.2/)
   42 FORMAT(2X,'VIB-KINETIC ENERGY: ',1PE17.9
     &,'    VIB-POTENTIAL ENERGY: '
     *,E17.9/2X,'VIB-TOTAL ENERGY:   ',1PE17.9)
   43 FORMAT(19X,'Q',37X,'P')
   44 FORMAT(F11.6,2F12.6,2X,3F12.6)
   45 FORMAT(2X,'ENERGY CONSERVATION',E17.9,'    KCAL/MOL')
      WRITE(6,1)
      WRITE(26,1)
      WRITE(6,*)'  ==== SUMMARY OF TRAJECTORY ===='
      WRITE(26,*)'  ==== SUMMARY OF TRAJECTORY ===='
      TLIFE=TIME*NC*10.0
      !#CZZ
      write(26,'(A15,A2,2X,A10,I3)')'FIN_PES:', current_U0, 
     &     'BOUNCES:',BOUNCE
      write(26,'(A15,2F14.7,2X,A15,F14.7)')'IMPACT_POS',RX0,RY0, 
     &     'MIN_Z_POS',z_pos_min
      !
      WRITE(6,30)NTZ,TLIFE
      WRITE(26,30)NTZ,TLIFE
      WRITE(6,2)NPATH
      WRITE(26,2)NPATH
      WRITE(26,45)HTMAX-HTMIN
      WRITE(26,*)
      
      !-----cZZ 2026.01.03 Erel for 1D model
      !Using C atom kinetic energy at the end to represent Erel
      EREL = NORM2(P(7:9))**2/2.0/w(3)/C1
      !-----
!  Bin, 2018/7/10
      IF (NSURF.GT.0.AND.NDELH(NPATH).NE.0) GOTO 999
!  End
      WRITE(6,3)
      WRITE(26,3)
      K=NATOMA(NPATH)
      IF (K.NE.1) THEN
         EVIB=EA(3)-EROTA
C
C.....Normal mode analysis added by Bin, 3/23/2015
C
C         PREPARATION FOR NORMAL MODE ANALYSIS
C         PRINT OUT THE CENTER OF MASS MOMENTA AND COORDINATES
C
         WRITE(26,42)EA(1)-EROTA,EA(2),EVIB
         WRITE(26,43)
         DO I=1,K
            J=LA(NPATH,I)*3
            J1=J-2
            WRITE(26,44)(QFINAL(J2),J2=J1,J),(PFINAL(J2),J2=J1,J)
         ENDDO
         WRITE(26,*)
C.....End
         WRITE(6,4)NTZ,EA(3),EVIB,EROTA,SDA,NTZ,AMA(4)
         WRITE(26,4)NTZ,EA(3),EVIB,EROTA,SDA,NTZ,AMA(4)
         IF (K.EQ.2) WRITE(6,22)NTZ,AN,AJ
         IF (K.EQ.2) WRITE(26,22)NTZ,AN,AJ
      ENDIF
      K=NATOMB(NPATH)
      IF (NSURF.GT.0) THEN 
         WRITE(6,6)
         WRITE(26,6)
         WRITE(6,7)NTZ,EREL,ERELSQ,NTZ,OAM(4),BF
         WRITE(26,7)NTZ,EREL,ERELSQ,NTZ,OAM(4),BF
         GOTO 100
      ENDIF
      IF (K.NE.1) THEN
         WRITE(6,5)
         WRITE(26,5)
         EVIB=EB(3)-EROTB
C
C.....Normal mode analysis added by Bin, 3/23/2015
C
C         PREPARATION FOR NORMAL MODE ANALYSIS
C         PRINT OUT THE CENTER OF MASS MOMENTA AND COORDINATES
C
         WRITE(26,42)EB(1)-EROTB,EB(2),EVIB
         WRITE(26,43)
         DO I=1,K
            J=LB(NPATH,I)*3
            J1=J-2
            WRITE(26,44)(QFINAL(J2),J2=J1,J),(PFINAL(J2),J2=J1,J)
         ENDDO
         WRITE(26,*)
C.....End
         WRITE(6,4)NTZ,EB(3),EVIB,EROTB,SDB,NTZ,AMB(4)
         WRITE(26,4)NTZ,EB(3),EVIB,EROTB,SDB,NTZ,AMB(4)
         IF (K.EQ.2) WRITE(6,22)NTZ,BN,BJ
         IF (K.EQ.2) WRITE(26,22)NTZ,BN,BJ
      ENDIF
      WRITE(6,6)
      WRITE(26,6)
      WRITE(6,7)NTZ,EREL,ERELSQ,NTZ,OAM(4),BF
      WRITE(26,7)NTZ,EREL,ERELSQ,NTZ,OAM(4),BF
      WRITE(6,8)
      WRITE(26,8)
      IF (NATOMA(NPATH).GT.1) WRITE(6,9)NTZ,ANG(1)
      IF (NATOMA(NPATH).GT.1) WRITE(26,9)NTZ,ANG(1)
      IF (NATOMB(NPATH).NE.1) THEN
         WRITE(6,10)NTZ,ANG(2)
         WRITE(26,10)NTZ,ANG(2)
         IF (NATOMA(NPATH).NE.1) WRITE(6,11)NTZ,ANG(3)
         IF (NATOMA(NPATH).NE.1) WRITE(26,11)NTZ,ANG(3)
      ENDIF
      IF (NATOMB(1).NE.0) THEN
         WRITE(6,12)NTZ,ANG(4),ANG(5)
         WRITE(26,12)NTZ,ANG(4),ANG(5)
         IF (NATOMA(NPATH).GT.1) WRITE(6,13)NTZ,ANG(6)
         IF (NATOMA(NPATH).GT.1) WRITE(26,13)NTZ,ANG(6)
         IF (NATOMB(NPATH).GT.1) WRITE(6,14)NTZ,ANG(7)
         IF (NATOMB(NPATH).GT.1) WRITE(26,14)NTZ,ANG(7)
         IF (AMAI(4).GE.1.00D-05) THEN
            WRITE(6,15)NTZ,ANG(8),ANG(9)
            WRITE(26,15)NTZ,ANG(8),ANG(9)
            IF (NATOMA(NPATH).GT.1) WRITE(6,16)NTZ,ANG(10)
            IF (NATOMA(NPATH).GT.1) WRITE(26,16)NTZ,ANG(10)
            IF (NATOMB(NPATH).GT.1) WRITE(6,17)NTZ,ANG(11)
            IF (NATOMB(NPATH).GT.1) WRITE(26,17)NTZ,ANG(11)
            IF (AMBI(4).LT.1.00D-05) GOTO 100
            WRITE(6,18)NTZ,ANG(12)
            WRITE(26,18)NTZ,ANG(12)
         ENDIF
         IF (AMBI(4).LT.1.00D-05) GOTO 100
         WRITE(6,19)NTZ,ANG(13),ANG(14)
         WRITE(26,19)NTZ,ANG(13),ANG(14)
         IF (NATOMA(NPATH).GT.1) WRITE(6,20)NTZ,ANG(15)
         IF (NATOMA(NPATH).GT.1) WRITE(26,20)NTZ,ANG(15)
         IF (NATOMB(NPATH).GT.1) WRITE(6,21)NTZ,ANG(16)
         IF (NATOMB(NPATH).GT.1) WRITE(26,21)NTZ,ANG(16)
      ENDIF
  100 WRITE(6,*)
      IF (NSURF .NE. 0) THEN
         WRITE(6,23)NTZ,ANG(17),ANG(18),ANG(19),ANG(20)
         WRITE(26,23)NTZ,ANG(17),ANG(18),ANG(19),ANG(20)
      ENDIF
      WRITE(9,38)NTZ,ERELSQ,OAMI(4),OAM(4),ANG(4)
      WRITE(10,38)NTZ,ETAI,ERAI,EA(3),EROTA,SDA,AMAI(4),AMA(4)
      WRITE(11,38)NTZ,ETBI,ERBI,EB(3),EROTB,SDB,AMBI(4),AMB(4)
      WRITE(17,36)NTZ,NCVMAX,VMAX
C      J=1
C      DO I=1,NATOMS
C      K=J+2
C      WRITE(17,37)(QVMAX(II),II=J,K),(PVMAX(II),II=J,K)
C      J=K+1
C      ENDDO
c     
      
!---> CZZ, For analysis; 2025.11.30
      AErelS(NTZ) = EREL
      AThtaS(NTZ) = ANG(19)
!--->
      CALL FLUSH(6)
      CALL FLUSH(9)
      CALL FLUSH(10)
      CALL FLUSH(11)
      CALL FLUSH(26)

C
999   CONTINUE
      RETURN
      END
